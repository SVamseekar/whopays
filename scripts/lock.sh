#!/usr/bin/env bash
# Regenerate requirements.lock: every dependency pinned except torch and the CUDA stack, which
# Colab and Kaggle preinstall (reinstalling costs minutes; the version used is logged per row).
# --exclude-newer keeps a one-week buffer behind brand-new releases; move it forward on purpose.
set -euo pipefail
cd "$(dirname "$0")/.."
EXCLUDE_NEWER="${EXCLUDE_NEWER:-2026-10-14}"
uv pip compile pyproject.toml --universal --python-version 3.11 \
  --extra gpu --extra stats --extra space --extra dev \
  --exclude-newer "$EXCLUDE_NEWER" --no-header --no-annotate --quiet \
  --no-emit-package torch --no-emit-package triton \
  | grep -vE '^(nvidia-|cuda-)' > requirements.lock.tmp
{ echo "# Generated by scripts/lock.sh (exclude-newer $EXCLUDE_NEWER). Do not edit."; cat requirements.lock.tmp; } > requirements.lock
rm requirements.lock.tmp
